"""New source evidence updates the existing incident, never fabricates a live fix."""

import hashlib
import json
import os
import time
from copy import deepcopy
from pathlib import Path

import httpx
from sqlmodel import Session

from stackos.db.models import RunPlanStepStatus
from stackos.mcp.bridge.diagnostics import emit_bridge_diagnostic
from stackos.repositories.run_plans import RunPlanRepository
from tests.helpers.internal_diagnostics import STAGES, incident, receipt
from tests.integration.test_repositories.test_internal_diagnostics import create_plan


def test_source_failure_receipt_updates_incident_without_live_repair(
    session: Session, project_id: int
) -> None:
    plan, started = create_plan(session, project_id)
    repo = RunPlanRepository(session)
    before = receipt("collect-classify", project_id, plan.id)
    # This event is generated by a synthetic source-test exception. It is not
    # the missing leaf exception from the user's actual failed host session.
    event = emit_bridge_diagnostic(
        phase="initialize",
        started_at=time.monotonic(),
        original=httpx.ReadTimeout("must-not-enter-receipt"),
    )
    encoded = json.dumps(event, sort_keys=True)
    assert "must-not-enter-receipt" not in encoded
    evidence_ref = (
        "source-test:bridge-diagnostic:sha256:" + hashlib.sha256(encoded.encode()).hexdigest()
    )
    checkpoints = []
    for stage, output_key in STAGES:
        repo.claim_step(run_plan_id=plan.id, run_id=started.run_id, step_id=stage)
        packet = receipt(stage, project_id, plan.id)
        packet["attempts"] = deepcopy(before["attempts"])
        if stage != "resume-provenance":
            packet["evidence_refs"].append(evidence_ref)
        if stage == "collect-classify":
            repo.record_step(
                run_plan_id=plan.id,
                run_id=started.run_id,
                step_id=stage,
                status=RunPlanStepStatus.BLOCKED,
                result_json={output_key: before},
                error="original_handshake_leaf_still_missing",
            )
            repo.claim_step(run_plan_id=plan.id, run_id=started.run_id, step_id=stage)
            packet["findings"].append(
                {
                    "finding_code": "source_test_safe_bridge_diagnostic_verified",
                    "layer": "mcp_bridge",
                    "classification": "observed",
                    "observed_at": event["observed_at"],
                    "evidence_refs": [evidence_ref],
                }
            )
        repo.record_step(
            run_plan_id=plan.id,
            run_id=started.run_id,
            step_id=stage,
            status=RunPlanStepStatus.SUCCESS,
            result_json={output_key: packet},
        )
        checkpoints.append(packet)
    final = repo.get(plan.id, project_id=project_id)
    conclusion = final.steps[-1].result_json["incident_receipt"]
    assert conclusion["attempts"] == before["attempts"]
    assert conclusion["status"] == "unresolved"
    assert conclusion["verification"]["symptom_check"] == "not_run"
    assert checkpoints[2]["remediation"]["disposition"] == "not_attempted"
    assert evidence_ref in conclusion["evidence_refs"]
    if output := os.environ.get("STACKOS_BRIDGE_DIAGNOSTIC_DEMO_OUT"):
        Path(output).write_text(
            json.dumps(
                {
                    "incident_key": incident()["case_id"],
                    "mode": "recorded",
                    "observation_origin": "synthetic source test, not the original host failure",
                    "source_test_event": event,
                    "source_evidence_ref": evidence_ref,
                    "same_run_plan": True,
                    "new_external_attempts": 0,
                    "live_packaged_reproduction": False,
                    "checkpoints": checkpoints,
                    "incident_status": "unresolved",
                },
                indent=2,
            )
            + "\n"
        )
